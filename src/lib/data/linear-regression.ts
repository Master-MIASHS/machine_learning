/**
 * Datasets of Part IV — Régression linéaire.
 *
 * `rows` layout: [response, predictor 1, …, predictor p] per observation,
 * matching the column order used by course_sources/sophie/*.pdf.
 */

/** A regression dataset: `columns` = [response, …predictors], `rows` aligned. */
export interface RegressionDataset {
	columns: string[];
	rows: number[][];
	/** Provenance and what the values were verified against. */
	source: string;
}

/** Response vector (first column of the rows). */
export function responseVector(ds: RegressionDataset): number[] {
	return ds.rows.map((r) => r[0]);
}

/** Predictor matrix (columns 1…p), optionally with an intercept column 0. */
export function designMatrix(ds: RegressionDataset, withInterceptCol = true): number[][] {
	return ds.rows.map((r) => (withInterceptCol ? [1, ...r.slice(1)] : r.slice(1)));
}

